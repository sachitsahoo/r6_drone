#!/usr/bin/env python3
"""Generate C++ and Python protocol bindings from the schema.

Runs at build time on a development machine or in CI. Never deployed to the robot, never
runs on the MCU, contributes no code size and no runtime dependency. See
docs/decisions/0003-schema-format-and-code-generation.md.

Output is deterministic: the same schema always produces byte-identical files, which is
what lets tests/python/test_generator.py pin the output and turn a generator change into a
reviewable diff instead of a silent one.

Usage:
    python3 protocol/generate.py [--out-dir protocol/generated] [--check]

    --check  regenerate into memory and exit non-zero if the files on disk differ.
             Used by CI and by the golden-output test.
"""

